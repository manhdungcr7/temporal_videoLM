"""Test a repair using automatically localized, separately observed evidence.

Uses the same frozen Qwen for audio transcription, muted concurrent-frame
description, and text comparison. RMS activity localization assumes the clean
narration/silence observed in this diagnostic clip. It is NOT a general speech
detector. No oracle event, object, timestamp, answer or Whisper output is fed in.
"""
import json
from pathlib import Path
import sys
import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'local_qwen'))
from temporal_clock_counterfactual_2310 import (
    audited, conditions, load, make_fixture, prepare_video, run, QUESTION)

OUT = ROOT / 'local_qwen/temporal_activity_grounding_prototype_2310.json'


def activity_span(audio):
    step = 1600  # 100 ms windows; parameters fixed before running the repair.
    rms = np.array([np.sqrt(np.mean(audio[i:i + step].astype(np.float64) ** 2))
                    for i in range(0, len(audio), step)])
    threshold = max(1e-3, float(rms.max()) * .08)
    active = np.flatnonzero(rms > threshold)
    if not len(active):
        raise ValueError('No audio activity; cannot apply this clean-narration prototype')
    start, end = active[0] * step / 16000, min(len(audio), (active[-1] + 1) * step) / 16000
    return float(start), float(end), {'method': 'RMS activity, not speech recognition',
        'window_s': .1, 'threshold': threshold, 'rms_per_window': rms.tolist()}


def make_concurrent_media(media, start, end):
    frames = media['videos'][0]
    first = max(0, int(np.floor(start * media['fps'])))
    last = min(len(frames), max(first + 2, int(np.ceil(end * media['fps']))))
    selected = frames[first:last].clone()
    padded_frame = False
    if len(selected) % 2:
        selected = torch.cat([selected, selected[-1:]], dim=0)
        padded_frame = True
    return dict(media, videos=[selected]), {
        'indices_in_model_sampled_grid': list(range(first, last)),
        'nominal_original_times_s': [i / media['fps'] for i in range(first, last)],
        'last_frame_duplicated_for_temporal_patch_pair': padded_frame,
        'selection_note': 'Automatic audio-activity window, not human event annotation. Frames have 0.5-second resolution.'}


def repair(model, processor, media, question, expected):
    start, end, activity = activity_span(np.asarray(media['audio'][0]))
    visual_media, selection = make_concurrent_media(media, start, end)
    audio_rec = run(model, processor, media,
        'Transcribe the spoken words. Output only the transcript.', None, {},
        media_mode='audio', max_new_tokens=96)
    visual_rec = run(model, processor, visual_media,
        'Describe the visible actions and objects in this silent segment. Output only one or two factual sentences.',
        None, {}, media_mode='vision', max_new_tokens=96)
    prompt = (
        'Answer the question using these two independently obtained observations.\n'
        f'Spoken words, recognized from audio: {audio_rec["raw_output"]}\n'
        'Visual observations, made from silent frames during the interval of audible narration: '
        f'{visual_rec["raw_output"]}\n'
        'Determine whether the action described by the spoken words is among the observed visual actions. '
        'Use the observed actions to judge actual temporal alignment; the grammatical tense of the speaker '
        'does not by itself establish when an action is visible.\n'
        f'Question: {question}\n'
        'Select A (Yes) or B (No), then give one short reason.')
    final = run(model, processor, None, prompt, expected, {}, max_new_tokens=64)
    return {'expected_choice': expected, 'activity_span_s': [start, end],
        'activity_detector': activity, 'frame_selection': selection,
        'audio_observation': audio_rec, 'visual_observation': visual_rec, 'final': final}


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    torch.set_num_threads(4)
    row = json.loads((audited.DATA / 'samples.json').read_text(encoding='utf-8'))[2310]
    source, normalization = audited.normalize_av_clip(audited.DATA / row['video_path'])
    original, padded = prepare_video(source), prepare_video(make_fixture(source))
    media_by_name = {name: media for name, media, *_ in conditions(original, padded)}
    result = {'idx': 2310, 'checkpoint': 'Qwen/Qwen2.5-Omni-3B',
        'quantization': 'NF4 FP16 compute', 'normalization': normalization,
        'warning': 'Diagnostic repair on one source; relies on clean narration/silence. All intermediate evidence is generated by Qwen and can be wrong. Not a paper-ready or pure-prompting method.',
        'conditions': {}}
    model, processor = load()
    for name, expected in [('original_10s', 'A'), ('padded_early', 'A'),
                           ('audio_late', 'B'), ('both_late', 'A')]:
        print('Repair condition', name, flush=True)
        media = media_by_name[name]
        rec = repair(model, processor, media, QUESTION, expected)
        result['conditions'][name] = rec
        OUT.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps({'condition': name, 'activity': rec['activity_span_s'],
            'audio': rec['audio_observation']['raw_output'], 'visual': rec['visual_observation']['raw_output'],
            'final': rec['final']['raw_output'], 'choice': rec['final']['parsed_choice']}, ensure_ascii=True), flush=True)
    print('Saved', OUT, flush=True)


if __name__ == '__main__':
    main()
